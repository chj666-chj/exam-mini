class Command(BaseCommand):
    help = "Seed knowledge base documents into the knowledgebase collection"

    def add_arguments(self, parser):
        parser.add_argument(
            '--reset',
            action='store_true',
            help='Clear knowledgebase collection before seeding',
        )

    def handle(self, *args, **options):
        if options['reset']:
            deleted, _ = Document.objects.filter(collection='knowledgebase').delete()
            self.stdout.write(self.style.WARNING(f'Cleared {deleted} existing knowledgebase documents'))

        created = 0
        skipped = 0
        for doc_data in DOCUMENTS:
            doc_id = doc_data['_id']
            doc_data_copy = dict(doc_data)
            del doc_data_copy['_id']

            _, was_created = Document.objects.update_or_create(
                collection='knowledgebase',
                doc_id=doc_id,
                defaults={'data': doc_data_copy}
            )
            if was_created:
                created += 1
            else:
                skipped += 1

        self.stdout.write(
            self.style.SUCCESS(
                f'Knowledge base seeding complete: {created} created, {skipped} updated, '
                f'{len(DOCUMENTS)} total documents'
            )
        )
