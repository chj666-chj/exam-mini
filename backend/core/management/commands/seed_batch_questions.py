def make_q(_id, title, qtype, difficulty, examid, options, answer,
           explanation, typename=None, score=0):
    """构造一条 question 文档（与 seed_exam_data 格式一致）。"""
    type_map = {"single": "单选题", "multiple": "多选题", "judge": "判断题",
                "fill": "填空题", "qa": "问答题"}
    return {
        "_id": _id,
        "title": title,
        "qtype": qtype,
        "type": qtype,
        "typename": typename or type_map.get(qtype, qtype),
        "typecode": qtype,
        "difficulty": difficulty,
        "examid": examid,
        "chapter": examid,
        "answer": answer,
        "explanation": explanation,
        "comments": explanation,
        "options": options,
        "score": score,
    }


def dedup_key(q):
    """去重键：章节 + 题干归一化。"""
    title = q["title"].strip().lower()
    return (q["examid"], title)


def shuffle_options(opts, answer_codes):
    """打乱选项顺序，保持 answer 对应正确选项。"""
    correct = [o for o in opts if o["value"] == 1]
    wrong = [o for o in opts if o["value"] == 0]
    random.shuffle(wrong)
    all_opts = correct + wrong
    random.shuffle(all_opts)
    # 重新分配 code A/B/C/D
    new_codes = ["A", "B", "C", "D", "E", "F"]
    new_answer = []
    for i, o in enumerate(all_opts):
        o["code"] = new_codes[i]
        if o["value"] == 1:
            new_answer.append(o["code"])
    return all_opts, "".join(sorted(new_answer))


