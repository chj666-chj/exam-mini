# ============================================================
# Management Command
# ============================================================

class Command(BaseCommand):
    help = '批量生成题库与测试试卷数据（每章节每题型60题）'

    def add_arguments(self, parser):
        parser.add_argument('--clean', action='store_true',
                            help='清空旧批量题库数据后重新生成')
        parser.add_argument('--questions', action='store_true',
                            help='仅生成题库')
        parser.add_argument('--papers', action='store_true',
                            help='仅生成试卷')

    def handle(self, *args, **options):
        do_clean = options['clean']
        do_questions = options['questions'] or not options['papers']
        do_papers = options['papers'] or not options['questions']

        if do_clean:
            deleted, _ = Document.objects.filter(
                collection='questions', doc_id__startswith='RK_'
            ).exclude(doc_id__regex=r'^RK_[A-Z]+_CH\d+_Q0[0-5]$').delete()
            # 更精确：删除QS/QM/QJ前缀的题目
            for prefix in ['QS', 'QM', 'QJ']:
                d, _ = Document.objects.filter(
                    collection='questions', doc_id__contains=f'_{prefix}'
                ).delete()
            # 删除批量试卷
            d2, _ = Document.objects.filter(
                collection='exam', doc_id__startswith='PAPER_'
            ).delete()
            self.stdout.write(self.style.WARNING(f'已清理旧批量数据'))

        stats = {}

        if do_questions:
            self.stdout.write(self.style.HTTP_INFO('\n=== 生成题库 ==='))
            total_questions = 0
            for chapter_id, gen_func in CHAPTER_GENERATORS.items():
                questions = gen_func()
                seen_keys = set()
                saved = 0
                skipped = 0
                for q in questions:
                    key = dedup_key(q)
                    if key in seen_keys:
                        skipped += 1
                        continue
                    seen_keys.add(key)
                    doc_id = q.pop('_id')
                    Document.objects.update_or_create(
                        collection='questions', doc_id=doc_id,
                        defaults={'data': q},
                    )
                    saved += 1
                    total_questions += 1
                stats[chapter_id] = {'total': saved, 'skipped': skipped}
                type_counts = {}
                for q in questions:
                    t = q.get('qtype', 'unknown')
                    type_counts[t] = type_counts.get(t, 0) + 1
                type_str = ' / '.join(f'{k}:{v}' for k, v in sorted(type_counts.items()))
                self.stdout.write(
                    f"  {chapter_id:<18} {saved:>3} 题  (跳过重复:{skipped})  [{type_str}]"
                )
            self.stdout.write(self.style.SUCCESS(
                f'\n题库生成完成：共 {total_questions} 题'
            ))

        if do_papers:
            self.stdout.write(self.style.HTTP_INFO('\n=== 生成试卷 ==='))
            total_papers = 0
            for exam_id, exam_name in EXAM_NAMES.items():
                # 获取该学科所有章节
                chapters = list(CHAPTER_GENERATORS.keys())
                exam_chapters = [c for c in chapters if c.startswith(exam_id)]

                for config in PAPER_CONFIGS:
                    paper_id = f"PAPER_{exam_id}_{config['name_suffix']}"
                    paper_questions = []

                    for qtype, count in config['composition'].items():
                        # 从所有章节中均匀抽取题目
                        pool = []
                        for ch in exam_chapters:
                            qs = Document.objects.filter(
                                collection='questions', doc_id__startswith=f'{ch}_Q'
                            )
                            for q in qs:
                                qdata = q.to_client()
                                if qdata.get('qtype') == qtype:
                                    diff = qdata.get('difficulty', 3)
                                    if isinstance(diff, str):
                                        diff = int(diff) if diff.isdigit() else 3
                                    if diff in config['difficulty_range']:
                                        pool.append(qdata)

                        # 均匀抽取
                        random.shuffle(pool)
                        selected = pool[:count]
                        paper_questions.extend(selected)

                    # 计算总分
                    type_scores = {"single": 1, "multiple": 2, "judge": 1}
                    total_score = sum(
                        type_scores.get(q.get('qtype'), 1) for q in paper_questions
                    )

                    paper_data = {
                        'name': f"{exam_name} - {config['name_suffix']}",
                        'description': f"基于{exam_name}题库自动组卷，难度范围{config['difficulty_range']}",
                        'duration': config['duration'],
                        'questionTypes': [
                            {"type": k, "label": {"single": "单选题", "multiple": "多选题", "judge": "判断题"}[k],
                             "count": v, "score": type_scores.get(k, 1)}
                            for k, v in config['composition'].items()
                        ],
                        'totalScore': total_score,
                        'passScore': int(total_score * 0.6),
                        'category': f"{exam_name}模拟试卷",
                        'status': 'published',
                        'questionCount': len(paper_questions),
                        'questionIds': [q.get('_id', '') for q in paper_questions],
                        'questions': [q.get('_id', '') for q in paper_questions],
                        'createdBy': 'batch_generator',
                        'difficultyRange': config['difficulty_range'],
                    }

                    Document.objects.update_or_create(
                        collection='exam', doc_id=paper_id,
                        defaults={'data': paper_data},
                    )
                    total_papers += 1
                    self.stdout.write(
                        f"  {paper_data['name']:<30} {len(paper_questions):>3} 题  "
                        f"总分:{total_score}  时长:{config['duration']}分钟  "
                        f"难度:{config['difficulty_range']}"
                    )

            self.stdout.write(self.style.SUCCESS(
                f'\n试卷生成完成：共 {total_papers} 套'
            ))

        # 统计汇总
        self.stdout.write(self.style.HTTP_INFO('\n=== 数据统计 ==='))
        for exam_id, exam_name in EXAM_NAMES.items():
            exam_qs = Document.objects.filter(
                collection='questions', doc_id__startswith=f'{exam_id}_CH'
            )
            total = exam_qs.count()
            type_dist = {}
            diff_dist = {}
            for q in exam_qs:
                qdata = q.to_client()
                t = qdata.get('qtype', 'unknown')
                type_dist[t] = type_dist.get(t, 0) + 1
                d = qdata.get('difficulty', 0)
                diff_dist[d] = diff_dist.get(d, 0) + 1
            self.stdout.write(f"\n  {exam_name}:")
            self.stdout.write(f"    总题数: {total}")
            self.stdout.write(f"    题型分布: {type_dist}")
            self.stdout.write(f"    难度分布: {dict(sorted(diff_dist.items(), key=lambda x: str(x[0])))}")
            # 试卷数
            papers = Document.objects.filter(
                collection='exam', doc_id__startswith=f'PAPER_{exam_id}'
            ).count()
            self.stdout.write(f"    试卷数: {papers}")

        self.stdout.write(self.style.SUCCESS('\n=== 全部完成 ==='))
